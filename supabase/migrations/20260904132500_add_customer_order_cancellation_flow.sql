create or replace function public.get_order_cancellation_context(
  p_order_id uuid,
  p_customer_user_id uuid,
  p_guest_access_token_hash text
)
returns jsonb
language plpgsql
stable
security definer
set search_path to ''
as $function$
declare
  v_order public.orders%rowtype;
  v_request private.order_cancellation_requests%rowtype;
  v_mode text;
begin
  select * into v_order from public.orders where id=p_order_id;
  if not found then return null; end if;

  if p_customer_user_id is not null then
    if v_order.customer_user_id is distinct from p_customer_user_id then return null; end if;
  else
    if v_order.customer_user_id is not null
       or p_guest_access_token_hash is null
       or v_order.guest_access_token_hash is distinct from p_guest_access_token_hash then return null; end if;
  end if;

  select * into v_request
  from private.order_cancellation_requests cr
  where cr.order_id=v_order.id
  order by cr.submitted_at desc
  limit 1;

  if v_order.status='cancelled' then v_mode:='cancelled';
  elsif v_request.id is not null and v_request.status='requested' then v_mode:='pending_review';
  elsif v_order.status in ('received','confirmed') then v_mode:='direct';
  elsif v_order.status in ('preparing','ready_for_courier_pickup') then v_mode:='review';
  else v_mode:='unavailable';
  end if;

  return jsonb_build_object(
    'orderId',v_order.id,
    'orderNumber',v_order.order_number,
    'orderStatus',v_order.status,
    'mode',v_mode,
    'latestRequest',case when v_request.id is null then null else jsonb_build_object(
      'id',v_request.id,
      'status',v_request.status,
      'requiresAdminReview',v_request.requires_admin_review,
      'reason',v_request.reason_text,
      'submittedAt',v_request.submitted_at,
      'resolvedAt',v_request.resolved_at,
      'resolutionNote',v_request.resolution_note
    ) end
  );
end;
$function$;

create or replace function public.get_admin_order_cancellation_requests()
returns table(
  request_id uuid,
  order_id uuid,
  order_number text,
  requester_kind text,
  reason_text text,
  submitted_at timestamptz,
  order_status text,
  payment_status text,
  currency_code text,
  final_total text
)
language plpgsql
security definer
set search_path to ''
as $function$
begin
  if (select auth.uid()) is null or not (select private.is_super_admin()) then
    raise exception 'admin_required' using errcode='42501';
  end if;
  return query
  select cr.id,o.id,o.order_number,cr.requester_kind,cr.reason_text,cr.submitted_at,
         o.status,o.payment_status,o.currency_code,o.final_total::text
  from private.order_cancellation_requests cr
  join public.orders o on o.id=cr.order_id
  where cr.status='requested'
  order by cr.submitted_at asc,cr.id;
end;
$function$;

create or replace function public.admin_review_order_cancellation_request(
  p_request_id uuid,
  p_decision text,
  p_note text default null
)
returns table(request_id uuid,request_status text,order_status text,changed boolean)
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_user_id uuid:=(select auth.uid());
  v_request private.order_cancellation_requests%rowtype;
  v_cancel record;
  v_now timestamptz:=now();
begin
  if v_user_id is null or not (select private.is_super_admin()) then
    raise exception 'admin_required' using errcode='42501';
  end if;
  if p_decision not in ('approved','rejected') then raise exception 'invalid_cancellation_decision'; end if;

  select * into v_request
  from private.order_cancellation_requests cr
  where cr.id=p_request_id
  for update;
  if not found then raise exception 'cancellation_request_not_found'; end if;

  if v_request.status=p_decision then
    return query select v_request.id,v_request.status,
      (select o.status from public.orders o where o.id=v_request.order_id),false;
    return;
  end if;
  if v_request.status<>'requested' then raise exception 'invalid_cancellation_review_state'; end if;
  if not v_request.requires_admin_review then raise exception 'cancellation_review_not_required'; end if;

  if p_decision='approved' then
    select * into v_cancel from private.cancel_pending_cod_order(
      v_request.order_id,v_request.id,v_user_id,'admin_cancellation_approved'
    );
  end if;

  update private.order_cancellation_requests
  set status=p_decision,resolved_at=v_now,resolved_by_user_id=v_user_id,
      resolution_note=nullif(trim(p_note),''),updated_at=v_now
  where id=v_request.id;

  insert into private.order_cancellation_events(
    cancellation_request_id,order_id,event_type,event_source,actor_user_id,metadata
  ) values (
    v_request.id,v_request.order_id,'cancellation_'||p_decision,'admin',v_user_id,
    jsonb_build_object('note',nullif(trim(p_note),''))
  );

  if p_decision='approved' then
    insert into private.order_cancellation_events(
      cancellation_request_id,order_id,event_type,event_source,actor_user_id,metadata
    ) values (
      v_request.id,v_request.order_id,'order_cancelled','admin',v_user_id,
      jsonb_build_object('restored_quantity',v_cancel.restored_quantity)
    );
  end if;

  return query select v_request.id,p_decision,
    (select o.status from public.orders o where o.id=v_request.order_id),true;
end;
$function$;

