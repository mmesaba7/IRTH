create or replace function private.review_return_request(p_return_request_id uuid, p_decision text, p_note text default null)
returns table(return_request_id uuid, status text, changed boolean)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_status text;
  v_now timestamptz := now();
begin
  if v_user_id is null or not (select private.is_super_admin()) then raise exception 'admin_required' using errcode='42501'; end if;
  if p_decision not in ('approved','rejected') then raise exception 'invalid_return_decision'; end if;

  select rr.status into v_status from private.return_requests rr where rr.id=p_return_request_id for update;
  if not found then raise exception 'return_request_not_found'; end if;
  if v_status = p_decision then return query select p_return_request_id,v_status,false; return; end if;
  if v_status <> 'requested' then raise exception 'invalid_return_review_state'; end if;

  update private.return_requests
  set status=p_decision, reviewed_at=v_now, reviewed_by_user_id=v_user_id,
      review_note=nullif(trim(p_note),''), updated_at=v_now
  where id=p_return_request_id;

  insert into private.return_request_events(return_request_id,event_type,event_source,source_key,actor_user_id,metadata)
  values(p_return_request_id,'return_'||p_decision,'admin','return-'||p_decision||':'||p_return_request_id::text,v_user_id,'{}'::jsonb);

  return query select p_return_request_id,p_decision,true;
end;
$$;
revoke all on function private.review_return_request(uuid,text,text) from public, anon, authenticated, service_role;

