create table private.return_requests (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete restrict,
  customer_user_id uuid references auth.users(id) on delete set null,
  requester_kind text not null,
  status text not null default 'requested',
  submitted_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by_user_id uuid references auth.users(id) on delete set null,
  review_note text,
  received_at timestamptz,
  inspected_at timestamptz,
  inspection_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint return_requests_requester_kind_values check (requester_kind in ('authenticated_customer','guest_customer')),
  constraint return_requests_status_values check (status in ('requested','approved','rejected','received','inspected','refund_pending','partially_refunded','refunded')),
  constraint return_requests_review_consistency check (
    (status = 'requested' and reviewed_at is null and reviewed_by_user_id is null)
    or (status <> 'requested' and reviewed_at is not null and reviewed_by_user_id is not null)
  ),
  constraint return_requests_received_consistency check (
    (status in ('received','inspected','refund_pending','partially_refunded','refunded')) = (received_at is not null)
  ),
  constraint return_requests_inspected_consistency check (
    (status in ('inspected','refund_pending','partially_refunded','refunded')) = (inspected_at is not null)
  )
);

create table private.return_request_items (
  id uuid primary key default gen_random_uuid(),
  return_request_id uuid not null references private.return_requests(id) on delete restrict,
  order_item_id uuid not null references public.order_items(id) on delete restrict,
  quantity integer not null,
  reason_text text not null,
  restockable_quantity integer,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint return_request_items_quantity_positive check (quantity > 0),
  constraint return_request_items_reason_length check (length(trim(reason_text)) between 3 and 1000),
  constraint return_request_items_restockable_range check (
    restockable_quantity is null or (restockable_quantity >= 0 and restockable_quantity <= quantity)
  ),
  constraint return_request_items_request_order_item_unique unique (return_request_id, order_item_id)
);

create table private.return_request_events (
  id bigint generated by default as identity primary key,
  return_request_id uuid not null references private.return_requests(id) on delete restrict,
  event_type text not null,
  event_source text not null,
  source_key text not null unique,
  actor_user_id uuid references auth.users(id) on delete set null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint return_request_events_type_nonblank check (length(trim(event_type)) >= 3),
  constraint return_request_events_source_values check (event_source in ('customer','admin','system')),
  constraint return_request_events_source_key_nonblank check (length(trim(source_key)) >= 8),
  constraint return_request_events_metadata_object check (jsonb_typeof(metadata) = 'object')
);

create index return_requests_order_status_idx on private.return_requests(order_id, status);
create index return_request_items_order_item_idx on private.return_request_items(order_item_id);
create index return_request_events_request_created_idx on private.return_request_events(return_request_id, created_at);

revoke all on private.return_requests from public, anon, authenticated, service_role;
revoke all on private.return_request_items from public, anon, authenticated, service_role;
revoke all on private.return_request_events from public, anon, authenticated, service_role;
grant select on private.return_requests to service_role;
grant select on private.return_request_items to service_role;
grant select on private.return_request_events to service_role;

