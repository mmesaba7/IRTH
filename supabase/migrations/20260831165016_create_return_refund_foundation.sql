create or replace function private.create_return_request_common(
  p_order_id uuid,
  p_requester_kind text,
  p_requester_user_id uuid,
  p_guest_access_token_hash text,
  p_items jsonb
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order public.orders%rowtype;
  v_request_id uuid;
  v_item jsonb;
  v_order_item_id uuid;
  v_quantity integer;
  v_reason text;
  v_order_quantity integer;
  v_reserved_quantity integer;
begin
  if p_order_id is null then raise exception 'order_required'; end if;
  if p_requester_kind not in ('authenticated_customer','guest_customer') then raise exception 'invalid_requester_kind'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 50 then
    raise exception 'invalid_return_items';
  end if;

  select * into v_order from public.orders where id = p_order_id for update;
  if not found then raise exception 'order_not_found'; end if;
  if v_order.status = 'cancelled' then raise exception 'cancelled_order_not_returnable'; end if;

  if p_requester_kind = 'authenticated_customer' then
    if p_requester_user_id is null or v_order.customer_user_id is distinct from p_requester_user_id then
      raise exception 'return_order_access_denied' using errcode = '42501';
    end if;
  else
    if v_order.customer_user_id is not null
       or p_guest_access_token_hash is null
       or length(trim(p_guest_access_token_hash)) < 32
       or v_order.guest_access_token_hash is distinct from p_guest_access_token_hash then
      raise exception 'return_order_access_denied' using errcode = '42501';
    end if;
  end if;

  insert into private.return_requests(order_id, customer_user_id, requester_kind)
  values (p_order_id, v_order.customer_user_id, p_requester_kind)
  returning id into v_request_id;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    begin
      v_order_item_id := nullif(trim(v_item->>'orderItemId'),'')::uuid;
      v_quantity := (v_item->>'quantity')::integer;
      v_reason := trim(coalesce(v_item->>'reason',''));
    exception when others then
      raise exception 'invalid_return_item';
    end;

    if v_order_item_id is null or v_quantity is null or v_quantity <= 0 or length(v_reason) not between 3 and 1000 then
      raise exception 'invalid_return_item';
    end if;

    select oi.quantity into v_order_quantity
    from public.order_items oi
    where oi.id = v_order_item_id and oi.order_id = p_order_id;
    if not found then raise exception 'return_item_not_in_order'; end if;

    select coalesce(sum(ri.quantity),0)::integer into v_reserved_quantity
    from private.return_request_items ri
    join private.return_requests rr on rr.id = ri.return_request_id
    where ri.order_item_id = v_order_item_id
      and rr.status <> 'rejected';

    if v_quantity > (v_order_quantity - v_reserved_quantity) then
      raise exception 'return_quantity_exceeds_available';
    end if;

    begin
      insert into private.return_request_items(return_request_id, order_item_id, quantity, reason_text)
      values (v_request_id, v_order_item_id, v_quantity, v_reason);
    exception when unique_violation then
      raise exception 'duplicate_return_order_item';
    end;
  end loop;

  insert into private.return_request_events(return_request_id,event_type,event_source,source_key,actor_user_id,metadata)
  values (
    v_request_id,
    'return_requested',
    'customer',
    'return-requested:' || v_request_id::text,
    p_requester_user_id,
    jsonb_build_object('requester_kind', p_requester_kind)
  );

  return v_request_id;
end;
$$;

revoke all on function private.create_return_request_common(uuid,text,uuid,text,jsonb) from public, anon, authenticated, service_role;

