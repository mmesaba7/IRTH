create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique,
  market_id uuid not null references public.markets(id),
  customer_user_id uuid references auth.users(id) on delete set null,
  status text not null default 'received',
  payment_status text not null default 'pending',
  currency_code text not null,
  subtotal_before_promotions numeric not null,
  promotion_discount_total numeric not null default 0,
  coupon_discount_total numeric not null default 0,
  merchandise_subtotal numeric not null,
  shipping_fee numeric not null,
  final_total numeric not null,
  coupon_id uuid references public.coupons(id) on delete set null,
  coupon_code_snapshot text,
  idempotency_scope text not null,
  idempotency_key text not null,
  guest_access_token_hash text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint orders_money_non_negative check (
    subtotal_before_promotions >= 0 and
    promotion_discount_total >= 0 and
    coupon_discount_total >= 0 and
    merchandise_subtotal >= 0 and
    shipping_fee >= 0 and
    final_total >= 0
  ),
  constraint orders_guest_access_guard check (
    customer_user_id is not null or guest_access_token_hash is not null
  ),
  constraint orders_idempotency_unique unique (idempotency_scope, idempotency_key)
);

create table public.order_customer_details (
  order_id uuid primary key references public.orders(id) on delete cascade,
  recipient_name text not null,
  email text not null,
  phone text not null,
  country_code text not null,
  administrative_area text not null,
  city text not null,
  address_line1 text not null,
  delivery_notes text,
  created_at timestamptz not null default now()
);

create table public.order_artisan_groups (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  artisan_id uuid not null references public.artisan_profiles(id),
  fulfillment_status text not null default 'received',
  merchandise_subtotal numeric not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint order_artisan_groups_subtotal_non_negative check (merchandise_subtotal >= 0),
  constraint order_artisan_groups_order_artisan_unique unique (order_id, artisan_id)
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  artisan_group_id uuid not null references public.order_artisan_groups(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  artisan_id uuid not null references public.artisan_profiles(id),
  craft_id uuid not null references public.crafts(id),
  product_slug_snapshot text not null,
  product_name_ar_snapshot text,
  product_name_en_snapshot text not null,
  quantity integer not null,
  unit_price numeric not null,
  original_line_total numeric not null,
  promotion_id uuid references public.promotions(id) on delete set null,
  promotion_discount numeric not null default 0,
  promotion_funding_irth numeric not null default 0,
  promotion_funding_artisan numeric not null default 0,
  coupon_discount numeric not null default 0,
  coupon_funding_irth numeric not null default 0,
  coupon_funding_artisan numeric not null default 0,
  line_total numeric not null,
  commission_rate_percent numeric(5,2) not null,
  created_at timestamptz not null default now(),
  constraint order_items_quantity_positive check (quantity > 0),
  constraint order_items_money_non_negative check (
    unit_price >= 0 and
    original_line_total >= 0 and
    promotion_discount >= 0 and
    promotion_funding_irth >= 0 and
    promotion_funding_artisan >= 0 and
    coupon_discount >= 0 and
    coupon_funding_irth >= 0 and
    coupon_funding_artisan >= 0 and
    line_total >= 0
  ),
  constraint order_items_commission_rate_range check (
    commission_rate_percent >= 0 and commission_rate_percent <= 100
  )
);

create table public.shipments (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  artisan_group_id uuid not null references public.order_artisan_groups(id) on delete cascade,
  status text not null default 'pending',
  courier_code text,
  tracking_number text,
  tracking_url text,
  shipped_at timestamptz,
  delivered_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.order_status_history (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  status text not null,
  changed_by uuid references auth.users(id) on delete set null,
  source text not null default 'system',
  created_at timestamptz not null default now()
);

