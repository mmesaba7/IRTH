create table if not exists private.tax_configuration_history (
  id bigint generated by default as identity primary key,
  market_id uuid not null references public.markets(id) on delete restrict,
  previous_rate_percent numeric(5,2) not null,
  new_rate_percent numeric(5,2) not null,
  reason text,
  changed_by_user_id uuid references auth.users(id) on delete set null,
  changed_at timestamptz not null default now(),
  constraint tax_configuration_history_previous_rate_range check (previous_rate_percent between 0 and 100),
  constraint tax_configuration_history_new_rate_range check (new_rate_percent between 0 and 100),
  constraint tax_configuration_history_reason_length check (reason is null or char_length(reason) between 1 and 1000)
);

create index if not exists tax_configuration_history_market_changed_idx
  on private.tax_configuration_history(market_id, changed_at desc);
create index if not exists tax_configuration_history_changed_by_idx
  on private.tax_configuration_history(changed_by_user_id)
  where changed_by_user_id is not null;

