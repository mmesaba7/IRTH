create or replace function private.record_refund_tax_ledger_reversal()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_item record;
begin
  if old.status <> 'succeeded' and new.status = 'succeeded' then
    for v_item in
      select fi.*, oi.order_id, oi.artisan_group_id, oi.artisan_id, oi.tax_rate_percent
      from private.refund_items fi
      join public.order_items oi on oi.id = fi.order_item_id
      where fi.refund_id = new.id
      order by fi.id
    loop
      if exists (
        select 1 from private.artisan_settlement_ledger l
        where l.order_item_id = v_item.order_item_id
          and l.source = 'order_item_sale'
          and l.entry_type = 'tax_withheld'
      ) then
        insert into private.artisan_settlement_ledger(
          entry_key, order_id, order_item_id, artisan_group_id, artisan_id,
          currency_code, currency_minor_unit_scale, entry_type, amount,
          calculation_base_amount, rate_percent, source, reason, reference_code, effective_at
        ) values (
          'refund:' || new.id::text || ':' || v_item.order_item_id::text || ':tax',
          v_item.order_id, v_item.order_item_id, v_item.artisan_group_id, v_item.artisan_id,
          new.currency_code, new.currency_minor_unit_scale, 'refund_tax_reversal',
          v_item.tax_reversal_amount,
          null, v_item.tax_rate_percent,
          'return_refund', 'approved_return_refund', new.id::text, new.succeeded_at
        )
        on conflict (entry_key) do nothing;
      end if;
    end loop;
  end if;

  return new;
end;
$$;

revoke all on function private.record_refund_tax_ledger_reversal()
  from public, anon, authenticated, service_role;

drop trigger if exists refund_tax_ledger_reversal on private.refunds;
create trigger refund_tax_ledger_reversal
after update of status on private.refunds
for each row
execute function private.record_refund_tax_ledger_reversal();

create or replace function private.set_market_tax_rate(
  p_market_id uuid,
  p_rate_percent numeric,
  p_admin_user_id uuid,
  p_reason text default null
)
returns numeric
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_old_rate numeric(5,2);
  v_new_rate numeric(5,2);
  v_reason text := nullif(trim(p_reason),'');
begin
  perform private.require_super_admin_user(p_admin_user_id);

  if p_rate_percent is null or p_rate_percent < 0 or p_rate_percent > 100
     or p_rate_percent <> round(p_rate_percent,2) then
    raise exception 'invalid_tax_rate';
  end if;
  if v_reason is not null and char_length(v_reason) > 1000 then
    raise exception 'invalid_reason';
  end if;

  select m.tax_rate_percent into v_old_rate
  from public.markets m
  where m.id = p_market_id
  for update;
  if not found then raise exception 'market_not_found'; end if;

  v_new_rate := p_rate_percent::numeric(5,2);
  if v_old_rate = v_new_rate then return v_old_rate; end if;

  update public.markets
  set tax_rate_percent = v_new_rate,
      updated_at = now()
  where id = p_market_id;

  insert into private.tax_configuration_history(
    market_id, previous_rate_percent, new_rate_percent, reason, changed_by_user_id
  ) values (
    p_market_id, v_old_rate, v_new_rate, v_reason, p_admin_user_id
  );

  return v_new_rate;
end;
$$;

revoke all on function private.set_market_tax_rate(uuid,numeric,uuid,text)
  from public, anon, authenticated, service_role;

