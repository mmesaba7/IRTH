  add column if not exists tax_reversal_amount numeric not null default 0;

alter table private.refund_items
  drop constraint if exists refund_items_amounts_non_negative,
  drop constraint if exists refund_items_entitlement_matches,
  drop constraint if exists refund_items_amount_currency_scale;
alter table private.refund_items
  add constraint refund_items_amounts_non_negative check (
    merchandise_refund_amount >= 0
    and irth_subsidy_reversal_amount >= 0
    and commission_reversal_amount >= 0
    and tax_reversal_amount >= 0
    and artisan_entitlement_reversal_amount >= 0
  ),
  add constraint refund_items_entitlement_matches check (
    artisan_entitlement_reversal_amount =
      merchandise_refund_amount + irth_subsidy_reversal_amount - commission_reversal_amount - tax_reversal_amount
  ),
  add constraint refund_items_amount_currency_scale check (
    merchandise_refund_amount = round(merchandise_refund_amount, currency_minor_unit_scale)
    and irth_subsidy_reversal_amount = round(irth_subsidy_reversal_amount, currency_minor_unit_scale)
    and commission_reversal_amount = round(commission_reversal_amount, currency_minor_unit_scale)
    and tax_reversal_amount = round(tax_reversal_amount, currency_minor_unit_scale)
    and artisan_entitlement_reversal_amount = round(artisan_entitlement_reversal_amount, currency_minor_unit_scale)
  );

create or replace function private.snapshot_refund_item_tax_reversal()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order_qty integer;
  v_prior_qty integer;
  v_tax_total numeric;
  v_tax_amount numeric;
begin
  select oi.quantity
  into v_order_qty
  from public.order_items oi
  where oi.id = new.order_item_id;

  if not found or v_order_qty <= 0 then
    raise exception 'refund_order_item_snapshot_missing';
  end if;

  select coalesce(sum(fi.quantity),0)::integer
  into v_prior_qty
  from private.refund_items fi
  join private.refunds fr on fr.id = fi.refund_id
  where fi.order_item_id = new.order_item_id
    and fr.status in ('pending','succeeded');

  select -l.amount
  into v_tax_total
  from private.artisan_settlement_ledger l
  where l.order_item_id = new.order_item_id
    and l.source = 'order_item_sale'
    and l.entry_type = 'tax_withheld'
  limit 1;

  if v_tax_total is null then
    v_tax_total := 0;
  end if;

  v_tax_amount := round(v_tax_total * (v_prior_qty + new.quantity) / v_order_qty, new.currency_minor_unit_scale)
                - round(v_tax_total * v_prior_qty / v_order_qty, new.currency_minor_unit_scale);

  new.tax_reversal_amount := v_tax_amount;
  new.artisan_entitlement_reversal_amount := round(
    new.merchandise_refund_amount
    + new.irth_subsidy_reversal_amount
    - new.commission_reversal_amount
    - v_tax_amount,
    new.currency_minor_unit_scale
  );

  if new.artisan_entitlement_reversal_amount < 0 then
    raise exception 'refund_entitlement_reversal_invalid';
  end if;

  return new;
end;
$$;

revoke all on function private.snapshot_refund_item_tax_reversal()
  from public, anon, authenticated, service_role;

