create or replace function private.snapshot_order_item_tax()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_rate numeric(5,2);
  v_scale smallint;
  v_tax_base numeric;
begin
  select m.tax_rate_percent, m.currency_minor_unit_scale
  into v_rate, v_scale
  from public.orders o
  join public.markets m on m.id = o.market_id
  where o.id = new.order_id;

  if not found or v_scale is null or v_rate is null then
    raise exception 'tax_configuration_missing';
  end if;

  -- IRTH-funded discounts preserve Artisan economic entitlement, so the tax
  -- settlement base restores that subsidy before extracting inclusive tax.
  v_tax_base := round(
    new.line_total + new.promotion_funding_irth + new.coupon_funding_irth,
    v_scale
  );

  new.tax_rate_percent := v_rate;
  new.tax_calculation_base_amount := v_tax_base;
  new.tax_amount := case
    when v_rate = 0 then 0
    else round(v_tax_base * v_rate / (100 + v_rate), v_scale)
  end;

  return new;
end;
$$;

revoke all on function private.snapshot_order_item_tax()
  from public, anon, authenticated, service_role;

drop trigger if exists order_item_tax_snapshot on public.order_items;
create trigger order_item_tax_snapshot
before insert on public.order_items
for each row
execute function private.snapshot_order_item_tax();

