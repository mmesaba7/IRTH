create or replace function private.require_artisan_payout_requester(
  p_artisan_id uuid,
  p_user_id uuid
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_auth_user_id uuid;
  v_has_role boolean;
begin
  if p_artisan_id is null or p_user_id is null then
    raise exception 'artisan_and_requester_required' using errcode='42501';
  end if;

  select ap.auth_user_id into v_auth_user_id
  from public.artisan_profiles ap
  where ap.id = p_artisan_id
  for update;

  if not found or v_auth_user_id is distinct from p_user_id then
    raise exception 'artisan_payout_account_access_denied' using errcode='42501';
  end if;

  select exists (
    select 1
    from public.user_roles ur
    join public.roles r on r.id = ur.role_id
    where ur.user_id = p_user_id and r.code = 'artisan'
  ) into v_has_role;

  if not v_has_role then
    raise exception 'artisan_role_required' using errcode='42501';
  end if;
end;
$$;

revoke all on function private.require_artisan_payout_requester(uuid,uuid)
from public, anon, authenticated, service_role;

create or replace function private.submit_bank_transfer_payout_account_request(
  p_artisan_id uuid,
  p_requested_by_user_id uuid,
  p_details_ciphertext text,
  p_details_fingerprint text,
  p_encryption_key_version integer
)
returns table(payout_account_id uuid, status text, changed boolean)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_pending_id uuid;
  v_pending_fingerprint text;
  v_active_id uuid;
  v_active_fingerprint text;
  v_account_id uuid;
begin
  perform private.require_artisan_payout_requester(p_artisan_id, p_requested_by_user_id);

  if p_details_ciphertext is null or length(p_details_ciphertext) not between 24 and 20000 then
    raise exception 'invalid_payout_account_ciphertext';
  end if;
  if p_details_fingerprint is null or p_details_fingerprint !~ '^[0-9a-f]{64}$' then
    raise exception 'invalid_payout_account_fingerprint';
  end if;
  if p_encryption_key_version is null or p_encryption_key_version < 1 then
    raise exception 'invalid_payout_account_key_version';
  end if;

  select a.id, a.details_fingerprint
  into v_pending_id, v_pending_fingerprint
  from private.artisan_payout_accounts a
  where a.artisan_id = p_artisan_id
    and a.method = 'bank_transfer'
    and a.status = 'pending_verification'
  for update;

  if found then
    if v_pending_fingerprint = p_details_fingerprint then
      return query select v_pending_id, 'pending_verification'::text, false;
      return;
    end if;
    raise exception 'payout_account_verification_already_pending';
  end if;

  select a.id, a.details_fingerprint
  into v_active_id, v_active_fingerprint
  from private.artisan_payout_accounts a
  where a.artisan_id = p_artisan_id
    and a.method = 'bank_transfer'
    and a.status = 'active'
  for share;

  if found and v_active_fingerprint = p_details_fingerprint then
    return query select v_active_id, 'active'::text, false;
    return;
  end if;

  insert into private.artisan_payout_accounts(
    artisan_id, method, status, details_ciphertext, details_fingerprint,
    encryption_key_version, requested_by_user_id
  ) values (
    p_artisan_id, 'bank_transfer', 'pending_verification', p_details_ciphertext,
    p_details_fingerprint, p_encryption_key_version, p_requested_by_user_id
  ) returning id into v_account_id;

  insert into private.payout_account_events(
    payout_account_id,event_type,event_source,source_key,actor_user_id,metadata
  ) values (
    v_account_id,'payout_account_submitted','artisan',
    'payout-account-submitted:'||v_account_id::text,
    p_requested_by_user_id,
    jsonb_build_object('method','bank_transfer','is_change_request',v_active_id is not null)
  );

  return query select v_account_id, 'pending_verification'::text, true;
end;
$$;

revoke all on function private.submit_bank_transfer_payout_account_request(uuid,uuid,text,text,integer)
from public, anon, authenticated, service_role;

