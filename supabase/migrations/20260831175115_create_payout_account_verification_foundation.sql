-- M6.1 — Payout Account + Verification Foundation
-- Approved: Bank Transfer is the first payout method.
-- Sensitive payout details are stored only as opaque encrypted payloads.
-- Any add/change stays Pending Verification until IRTH approval.

create or replace function private.is_super_admin_user(p_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.user_roles ur
    join public.roles r on r.id = ur.role_id
    where ur.user_id = p_user_id
      and r.code = 'super_admin'
  );
$$;

revoke all on function private.is_super_admin_user(uuid)
from public, anon, authenticated, service_role;

create table private.artisan_payout_accounts (
  id uuid primary key default gen_random_uuid(),
  artisan_id uuid not null references public.artisan_profiles(id) on delete restrict,
  method text not null,
  status text not null default 'pending_verification',
  details_ciphertext text not null,
  details_fingerprint text not null,
  encryption_key_version integer not null,
  requested_by_user_id uuid not null references auth.users(id) on delete restrict,
  requested_at timestamptz not null default now(),
  reviewed_by_user_id uuid references auth.users(id) on delete restrict,
  reviewed_at timestamptz,
  review_note text,
  activated_at timestamptz,
  superseded_by_account_id uuid references private.artisan_payout_accounts(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint artisan_payout_accounts_method_values
    check (method in ('bank_transfer')),
  constraint artisan_payout_accounts_status_values
    check (status in ('pending_verification','active','rejected','superseded')),
  constraint artisan_payout_accounts_ciphertext_length
    check (length(details_ciphertext) between 24 and 20000),
  constraint artisan_payout_accounts_fingerprint_format
    check (details_fingerprint ~ '^[0-9a-f]{64}$'),
  constraint artisan_payout_accounts_key_version_positive
    check (encryption_key_version >= 1),
  constraint artisan_payout_accounts_review_note_length
    check (review_note is null or length(trim(review_note)) between 1 and 2000),
  constraint artisan_payout_accounts_state_consistency
    check (
      (status = 'pending_verification'
        and reviewed_by_user_id is null and reviewed_at is null
        and activated_at is null and superseded_by_account_id is null)
      or
      (status = 'active'
        and reviewed_by_user_id is not null and reviewed_at is not null
        and activated_at is not null and superseded_by_account_id is null)
      or
      (status = 'rejected'
        and reviewed_by_user_id is not null and reviewed_at is not null
        and activated_at is null and superseded_by_account_id is null)
      or
      (status = 'superseded'
        and reviewed_by_user_id is not null and reviewed_at is not null
        and activated_at is not null and superseded_by_account_id is not null)
    ),
  constraint artisan_payout_accounts_not_self_superseded
    check (superseded_by_account_id is null or superseded_by_account_id <> id)
);

create unique index artisan_payout_accounts_one_pending_per_method
  on private.artisan_payout_accounts(artisan_id, method)
  where status = 'pending_verification';

create unique index artisan_payout_accounts_one_active_per_method
  on private.artisan_payout_accounts(artisan_id, method)
  where status = 'active';

create index artisan_payout_accounts_artisan_status_idx
  on private.artisan_payout_accounts(artisan_id, status, created_at desc);

create table private.payout_account_events (
  id bigint generated by default as identity primary key,
  payout_account_id uuid not null references private.artisan_payout_accounts(id) on delete restrict,
  event_type text not null,
  event_source text not null,
  source_key text not null unique,
  actor_user_id uuid references auth.users(id) on delete set null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint payout_account_events_type_nonblank check (length(trim(event_type)) >= 3),
  constraint payout_account_events_source_values check (event_source in ('artisan','admin','system')),
  constraint payout_account_events_source_key_nonblank check (length(trim(source_key)) >= 8),
  constraint payout_account_events_metadata_object check (jsonb_typeof(metadata) = 'object')
);

create index payout_account_events_account_created_idx
  on private.payout_account_events(payout_account_id, created_at);

revoke all on private.artisan_payout_accounts from public, anon, authenticated, service_role;
revoke all on private.payout_account_events from public, anon, authenticated, service_role;
revoke all on sequence private.payout_account_events_id_seq from public, anon, authenticated, service_role;

create or replace function private.prevent_payout_account_sensitive_mutation()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.artisan_id is distinct from new.artisan_id
     or old.method is distinct from new.method
     or old.details_ciphertext is distinct from new.details_ciphertext
     or old.details_fingerprint is distinct from new.details_fingerprint
     or old.encryption_key_version is distinct from new.encryption_key_version
     or old.requested_by_user_id is distinct from new.requested_by_user_id
     or old.requested_at is distinct from new.requested_at
     or old.created_at is distinct from new.created_at then
    raise exception 'payout_account_sensitive_fields_are_immutable';
  end if;
  return new;
end;
$$;

revoke all on function private.prevent_payout_account_sensitive_mutation()
from public, anon, authenticated, service_role;

create trigger artisan_payout_accounts_sensitive_immutable
before update on private.artisan_payout_accounts
for each row execute function private.prevent_payout_account_sensitive_mutation();

