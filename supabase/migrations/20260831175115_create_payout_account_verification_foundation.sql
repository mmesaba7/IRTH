create or replace function public.get_artisan_payout_account_status(
  p_artisan_id uuid,
  p_requester_user_id uuid
)
returns table(
  payout_account_id uuid,
  method text,
  status text,
  requested_at timestamptz,
  reviewed_at timestamptz,
  activated_at timestamptz,
  review_note text
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform private.require_artisan_payout_requester(p_artisan_id,p_requester_user_id);
  return query
  select a.id,a.method,a.status,a.requested_at,a.reviewed_at,a.activated_at,a.review_note
  from private.artisan_payout_accounts a
  where a.artisan_id=p_artisan_id
    and a.status in ('pending_verification','active','rejected')
  order by case a.status when 'pending_verification' then 1 when 'active' then 2 else 3 end,
           a.created_at desc;
end;
$$;

revoke all on function public.get_artisan_payout_account_status(uuid,uuid)
from public, anon, authenticated, service_role;
grant execute on function public.get_artisan_payout_account_status(uuid,uuid)
to service_role;

create or replace function public.get_payout_accounts_for_admin(
  p_admin_user_id uuid,
  p_artisan_id uuid default null
)
returns table(
  payout_account_id uuid,
  artisan_id uuid,
  method text,
  status text,
  details_ciphertext text,
  details_fingerprint text,
  encryption_key_version integer,
  requested_by_user_id uuid,
  requested_at timestamptz,
  reviewed_by_user_id uuid,
  reviewed_at timestamptz,
  review_note text,
  activated_at timestamptz,
  superseded_by_account_id uuid
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_admin_user_id is null or not private.is_super_admin_user(p_admin_user_id) then
    raise exception 'admin_required' using errcode='42501';
  end if;
  return query
  select a.id,a.artisan_id,a.method,a.status,a.details_ciphertext,a.details_fingerprint,
         a.encryption_key_version,a.requested_by_user_id,a.requested_at,
         a.reviewed_by_user_id,a.reviewed_at,a.review_note,a.activated_at,
         a.superseded_by_account_id
  from private.artisan_payout_accounts a
  where p_artisan_id is null or a.artisan_id=p_artisan_id
  order by a.created_at desc;
end;
$$;

