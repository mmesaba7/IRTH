create or replace function private.review_payout_account_request(
  p_payout_account_id uuid,
  p_decision text,
  p_admin_user_id uuid,
  p_review_note text default null
)
returns table(payout_account_id uuid, status text, changed boolean)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_account private.artisan_payout_accounts%rowtype;
  v_old_active_id uuid;
  v_now timestamptz := now();
  v_target_status text;
begin
  if p_admin_user_id is null or not private.is_super_admin_user(p_admin_user_id) then
    raise exception 'admin_required' using errcode='42501';
  end if;
  if p_decision not in ('approved','rejected') then
    raise exception 'invalid_payout_account_decision';
  end if;
  if p_review_note is not null and length(trim(p_review_note)) not between 1 and 2000 then
    raise exception 'invalid_payout_account_review_note';
  end if;

  select a.* into v_account
  from private.artisan_payout_accounts a
  where a.id = p_payout_account_id
  for update;
  if not found then raise exception 'payout_account_not_found'; end if;

  v_target_status := case when p_decision='approved' then 'active' else 'rejected' end;

  if v_account.status = v_target_status then
    return query select v_account.id, v_account.status, false;
    return;
  end if;
  if v_account.status <> 'pending_verification' then
    raise exception 'invalid_payout_account_review_state';
  end if;

  if p_decision = 'approved' then
    select a.id into v_old_active_id
    from private.artisan_payout_accounts a
    where a.artisan_id = v_account.artisan_id
      and a.method = v_account.method
      and a.status = 'active'
      and a.id <> v_account.id
    for update;

    if found then
      update private.artisan_payout_accounts a
      set status='superseded', superseded_by_account_id=v_account.id, updated_at=v_now
      where a.id=v_old_active_id;

      insert into private.payout_account_events(
        payout_account_id,event_type,event_source,source_key,actor_user_id,metadata
      ) values (
        v_old_active_id,'payout_account_superseded','admin',
        'payout-account-superseded:'||v_old_active_id::text||':'||v_account.id::text,
        p_admin_user_id,jsonb_build_object('replacement_account_id',v_account.id)
      );
    end if;

    update private.artisan_payout_accounts a
    set status='active', reviewed_by_user_id=p_admin_user_id, reviewed_at=v_now,
        review_note=nullif(trim(p_review_note),''), activated_at=v_now, updated_at=v_now
    where a.id=v_account.id;

    insert into private.payout_account_events(
      payout_account_id,event_type,event_source,source_key,actor_user_id,metadata
    ) values (
      v_account.id,'payout_account_approved','admin',
      'payout-account-approved:'||v_account.id::text,
      p_admin_user_id,'{}'::jsonb
    );
  else
    update private.artisan_payout_accounts a
    set status='rejected', reviewed_by_user_id=p_admin_user_id, reviewed_at=v_now,
        review_note=nullif(trim(p_review_note),''), updated_at=v_now
    where a.id=v_account.id;

    insert into private.payout_account_events(
      payout_account_id,event_type,event_source,source_key,actor_user_id,metadata
    ) values (
      v_account.id,'payout_account_rejected','admin',
      'payout-account-rejected:'||v_account.id::text,
      p_admin_user_id,'{}'::jsonb
    );
  end if;

  return query select v_account.id, v_target_status, true;
end;
$$;

revoke all on function private.review_payout_account_request(uuid,text,uuid,text)
from public, anon, authenticated, service_role;

